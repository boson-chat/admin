#!/bin/sh
# Writes .env for docker-compose.yml with fresh random dev secrets.
# Leaves an existing .env alone.
set -eu
cd "$(dirname "$0")/.."
if [ -f .env ]; then
	echo ".env exists; delete it to regenerate" >&2
	exit 0
fi
umask 077
{
	echo "# Generated by scripts/dev-env.sh for local development only."
	echo "COMPOSE_PROFILES=voice,metrics"
	echo "DB_PASSWORD=$(openssl rand -hex 16)"
	echo "AUTH_KEY_ENCRYPTION_KEY=$(openssl rand -base64 32)"
	echo "SESSION_KEY=$(openssl rand -base64 32)"
} > .env
echo "wrote .env"
